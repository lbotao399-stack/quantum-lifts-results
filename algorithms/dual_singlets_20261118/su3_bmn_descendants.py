def read_operator(path, expected):
    raw = gzip.decompress(path.read_bytes())
    if hashlib.sha256(raw).hexdigest() != expected:
        raise ValueError("unexpected source polynomial")
    data = json.loads(raw)
    result = {tuple(map(tuple, w)): Fraction(c) for c, w in data["terms"]}
    assert len(result) == data["n_terms"]
    return result


def flavour_root(expr, i, j, words):
    # E_ij acts on phi^j and on the dual fermion psi_i.
    @lru_cache(None)
    def on_trace(tr):
        vals = Counter()
        for index, letter in enumerate(tr):
            if letter == j:
                c, image = 1, i
            elif letter == 3+i:
                c, image = -1, 3+j
            else:
                continue
            sign, canonical = words.canon_word(tr[:index] + (image,) + tr[index+1:])
            if sign:
                vals[canonical] += sign*c
        return {w: n for w,n in vals.items() if n}
    vals = Counter()
    for multi, c in expr.items():
        for k, tr in enumerate(multi):
            for image, n in on_trace(tr).items():
                words.add_term(vals, multi[:k]+(image,)+multi[k+1:], c*n)
    return dict(vals)


def highest(expr, words):
    weight = words.expr_sector(expr)[1:]
    for i, j in ((1,2), (0,2), (0,1)):
        result = dict(expr)
        raised = expr
        coefficient = Fraction(1)
        for k in range(1, sum(weight)+2):
            raised = flavour_root(raised, i, j, words)
            if not raised:
                break
            coefficient /= -k * (weight[i]-weight[j]+j-i+k)
            term = raised
            for _ in range(k):
                term = flavour_root(term, j, i, words)
            add_scaled(result, term, coefficient)
        else:
            raise ValueError("flavour string exceeds the total degree")
        expr = result
    assert not flavour_root(expr,0,1,words) and not flavour_root(expr,1,2,words)
    return expr


def witness(expr, sector, words):
    # The SO(3)-invariant tensors for SU(2) adjoints are generated by the
    # metric and the alternating tensor. Traces of lengths 2 and 3 span.
    value = polynomial(expr)
    assert not polynomial(words.Q_expr(expr))
    parents = words.words_of_sector((sector[0]+1, *sector[1:]), 3)
    basis = boundary_basis(parents, words)
    remainder, _ = reduce_row(value,basis)
    result = dict(active_sector=sector, active_coordinates=len(value),
                  predecessor_trace_words=len(parents), rational_boundary_rank=len(basis),
                  rational_class_nonzero=bool(remainder))
    if remainder:
        ell = residue_functional(basis,min(remainder))
        coefficient = pairing(ell, value)
        assert coefficient and all(not pairing(ell, polynomial(words.Q_multi(w))) for w in parents)
        result.update(pairing=str(coefficient), functional=[[e,o,str(c)] for (e,o),c in sorted(ell.items())])
    return result


def verify_classical(source, words, executable):
    raw = words.Q_expr(source)
    groups = defaultdict(dict)
    for multi,c in raw.items():
        key = tuple(sorted(x for tr in multi for x in tr))
        groups[key][multi] = c
    records = []
    with TemporaryDirectory() as folder:
        root = Path(folder)
        for key,rows in sorted(groups.items()):
            scalar = max(range(3), key=key.count)
            den = lcm(*(c.denominator for c in rows.values()))
            with (root/"words").open("w") as stream:
                print(scalar, "030405", len(rows), file=stream)
                for w,c in sorted(rows.items()):
                    print(int(c*den), len(w), *(bytes(tr).hex() for tr in w), file=stream)
            subprocess.run([str(executable.resolve()), str(root/"words"), str(root/"result"),
                            str(len(key))], check=True)
            record = json.loads((root/"result").read_bytes())
            assert record["formal_words"] == len(rows) and record["nonzero_monomials"] == 0
            assert record["contributions"] and record["sum_abs_actual"] <= record["sum_abs_bounds"]
            records.append(dict(content=key, diagonal_scalar=scalar, denominator=den, **record))
    return dict(source_trace_terms=len(source), classical_variation_terms=len(raw), contents=records)


def descendants(parent, words):
    assert not even_part(parent, words) and words.expr_sector(parent) == (5,7,4,4)
    assert not flavour_root(parent,0,1,words) and not flavour_root(parent,1,2,words)
    raised = restrict_block(parent, (3,0,0), words)
    for axis in range(3):
        raised = words.Qplus_expr(raised, axis)
    assert words.expr_sector(raised) == (8,5,5,5)
    triple = witness(raised, (8,5,5,5), words)
    product = {}
    for j in range(3):
        component = parent if j == 0 else flavour_root(parent,j,0,words)
        term = words.mul_expr(words.v_gen((0,),j), component)
        add_scaled(product, term, Fraction(1) if j==0 else Fraction(1,3))
    assert words.expr_sector(product) == (6,8,5,5)
    assert not flavour_root(product,0,1,words) and not flavour_root(product,1,2,words)
    assert not even_part(product,words)
    mixed = restrict_block(product, (4,0,0), words, 3)
    product_witness = witness(mixed, (5,4,4,4), words)
    product_witness["full_trace_terms"] = len(product)
    return dict(level=36, weight=[8,5,5], C_odd_length10_triple_raising=triple,
                C_odd_length12_bilinear_product=product_witness)


def raised_level34(parent, words):
    assert even_part(parent,words)==parent and words.expr_sector(parent)==(6,8,5,4)
    raised = highest(words.Qplus_expr(parent,2),words)
    assert words.expr_sector(raised)==(7,8,5,5) and even_part(raised,words)==raised
    block = restrict_block(raised,(3,0,0),words,5)
    return dict(level=36, weight=[8,5,5], full_trace_terms=len(raised),
                C_even_length11_raised=witness(block,(6,4,4,5),words))


