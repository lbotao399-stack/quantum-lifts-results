@cache
def singlet_trace(cycles):
    left, right = [], []
    for k in sorted(cycles, reverse=True):
        (left if sum(left) <= sum(right) else right).append(k)
    a = decomposition("F4", tuple(left))
    b = decomposition("F4", tuple(right))
    return sum(n*b.get(w, 0) for w, n in a.items())


def blocks():
    # In the even-dotted convention the flavour rectangle is transposed.
    spin, flavour = (4,4), (3,3)
    signatures = [(tuple(sorted(a+b)), Fraction(character(spin,a)*character(flavour,b),
                                                   centralizer(a)*centralizer(b)))
                  for a in partitions(8) for b in partitions(6)]
    out = []
    for p in partitions(14):
        shape = p[::-1]
        coeff = sum(c*character(shape, cycles) for cycles,c in signatures)
        if not coeff:
            continue
        assert coeff == 1
        highest = (*shape[:2], *(max(0, sum(x >= j for x in shape)-2) for j in range(1,4)))
        shifted = tuple(x+d for x,d in zip(highest, (2,2,-2,-2,-2)))
        sizes = [multiplicity(shape, n, singlet_trace) for n in (12,13,14)]
        out.append(dict(shape=shape, shifted_highest=shifted, by_length_12_13_14=sizes,
                        reaches_target=shifted == (6,6,0,0,0)))
    selected = [r for r in out if r["reaches_target"]]
    assert len(out) == 10 and len(selected) == 1 and selected[0]["shape"] == (4,4,3,3)
    return out


def native_checks():
    c = Colour()
    metric = [[c.metric.get((i,j), 0) for j in range(52)] for i in range(52)]
    inverse = [[Fraction(str(c.inverse.get((i,j), 0))) for j in range(52)] for i in range(52)]
    g = Brackets(c.br, metric, inverse)
    pairs = ((0,0), (0,1), (0,c.data["raising"][0]), *zip(c.data["raising"],c.data["lowering"]),
             *zip(c.data["raising"],c.data["raising"][1:]))
    packet = json.loads((RETURN/"reverse_ward.json").read_bytes())
    # The two missing flavour choices are generated by the identical exact solve.
    for spin in (0,1):
        packet.append(solve(spin,0))
    out = []
    for record in sorted(packet, key=lambda r: (r["spin"],r["flavour"])):
        w = Ward(g, record["spin"], record["flavour"])
        count, _, _ = system(w, examples(4, (0,*c.data["raising"]), pairs), decode(record["coefficients"]))
        out.append(dict(spin=w.spin, flavour=w.flavour, native_equations=count))
    return out


def incoming_powers():
    # Twisting back from (p,p | 0,0,0) gives (p-r,p-r | r,r,r).
    # A positive third odd label requires the second even row to have length >=3.
    out = []
    for p in (5,6):
        allowed = []
        for r in range(1,p+1):
            if p-r < 3:
                continue
            s = (p-r,p-r)+(3,)*r
            n = sum(s)
            assert n == 2*p+r
            allowed.append(dict(order=r, shape=s,
                                dimensions=[multiplicity(s,k,singlet_trace) for k in (n-2,n-1,n)]))
        out.append(dict(power=p, allowed=allowed))
    assert out[0]["allowed"][1]["dimensions"] == [203,141,62]
    return out


