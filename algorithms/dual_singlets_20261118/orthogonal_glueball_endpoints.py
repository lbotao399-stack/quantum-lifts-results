"""Tree boundaries among determinant relations, and the full terminal singlets."""
import argparse
from collections import Counter
from fractions import Fraction
from functools import lru_cache
from itertools import permutations
import json
from pathlib import Path

from b2_schur_complex import centralizer, character, partitions, transpose
from orthogonal_glueball_sources import missing_adjoint_trace, physical_image_relations, relations
from terminal_commutators import generators, parity, sign


@lru_cache(None)
def character_terms(shape):
    return [(cycle, Fraction(value, centralizer(cycle)))
            for cycle in partitions(sum(shape)) if (value := character(shape, cycle))]


def physical_predecessor(colours, power, order):
    """Keep the distinguished second jet; branch its dotted and scalar indices."""
    dotted = power - order
    shapes = {
        'D2c': (transpose((dotted, dotted-2)), (order, order, order)),
        'Dphi': (transpose((dotted, dotted-1)), (order, order, order-1)),
        'psi': (transpose((dotted, dotted)), (order, order-1, order-1)),
    }
    result = {}
    for jet, (fermions, bosons) in shapes.items():
        total = Fraction()
        for left, first in character_terms(fermions):
            for right, second in character_terms(tuple(n for n in bosons if n)):
                total += first * second * missing_adjoint_trace(tuple(sorted((1,)+left+right)), colours)
        assert total.denominator == 1 and total >= 0
        result[jet] = int(total)
    return result


def terminal_weight(weight):
    """Count signed-permutation orbits by number of occupied Cartan sites."""
    if min(weight) < 0 or sum(weight) % 2:
        return {}
    # A pure two-ghost trace can occur arbitrarily often. Removing it leaves
    # at most the scalar degree many trace factors.
    pure = (1, 1, 0, 0, 0)
    words = [word for word in generators(weight) if word != pure]
    dp = {((0, 0, 0, 0, 0), 0): 1}
    for word in words:
        work = dict(dp)
        for (used, length), multiplicity in dp.items():
            room = min((cap-x)//step for cap, x, step in zip(weight, used, word) if step)
            if parity(word):
                room = min(room, 1)
            for count in range(1, room+1):
                target = tuple(x+count*step for x, step in zip(used, word))
                key = target, length+count
                work[key] = work.get(key, 0) + multiplicity
        dp = work
    coefficients = Counter()
    for (used, length), multiplicity in dp.items():
        rest = weight[0]-used[0]
        if used[2:] == weight[2:] and weight[1]-used[1] == rest:
            coefficients[length+rest] += multiplicity
    return coefficients


def terminal_singlet(power, order, rank):
    rho = (2, 1, 0)
    multiplicities = Counter()
    for spin, spin_sign in ((0, 1), (1, -1)):
        for perm in permutations(range(3)):
            weight = (power-order+spin, power-order-spin)
            weight += tuple(order+rho[i]-rho[perm[i]] for i in range(3))
            for sites, count in terminal_weight(weight).items():
                multiplicities[sites] += spin_sign * sign(perm) * count
    assert all(n >= 0 for n in multiplicities.values())
    all_sites = sum(multiplicities.values())
    finite = sum(n for k, n in multiplicities.items() if k <= rank)
    return dict(stable=all_sites, Cartan=finite, kernel=all_sites-finite,
                by_sites={k: n for k, n in sorted(multiplicities.items()) if n})


def invariant_monomials(degree):
    # Invariants of a 3 x 3 matrix under the two complex rotation groups
    # are freely generated by tr(T^t T), det(T) and e_2(T^t T).
    return [(degree-2*i-3*j-4*k, i, j, k)
            for k in range(degree//4+1) for j in range((degree-4*k)//3+1)
            for i in range((degree-4*k-3*j)//2+1)]


def endpoint(colours, power, order):
    assert colours == power+2*order+2 and order % 2
    total = 2*power+order
    shape = (power-order, power-order)+(3,)*order
    degree = power-order-3
    monomials = invariant_monomials(degree)
    source = physical_predecessor(colours, power, order)
    image = physical_image_relations(power, order, colours)
    assert sum(source.values()) == relations(shape, total-1, colours)
    assert source['psi'] == source['Dphi'] == 0
    assert len(monomials) == image == relations(shape, total, colours)
    # Replacing one T by the second ghost jet gives an invariant preimage.
    # The actual tree maps on ++, +-, -- are X^2, XY+YX, Y^2.
    # Their three-dimensional image is the complete symmetric dotted tensor.
    # Polarized Euler differentiation counts weighted T-degree, independently
    # of the choice of its coordinates.
    nonzero = [{ 'monomial': m, 'Euler_multiplier': degree-m[0]} for m in monomials if m[0]<degree]
    assert len(nonzero) <= sum(source.values())
    return dict(colours=colours, power=power, page_tested=order, physical_level=6*power,
                Taylor_diagram=shape, source_length=total-1, relation_length=total,
                physical_source_relations=source, physical_terminal_relations=image,
                monomial_order=['scalar_double_path','quadratic','determinant','quartic'],
                tree_images=nonzero, relation_tree_rank=len(nonzero),
                connecting_image_dimension=image-len(nonzero),
                surviving_relation_monomial=(degree,0,0,0))


def run():
    records = {}
    for colours, power, order in ((9,5,1), (10,6,1), (17,9,3), (18,10,3)):
        record = endpoint(colours, power, order)
        if order == 3:
            targets = {}
            for k in (0,1,2):
                if k:
                    assert physical_image_relations(power,k,colours) == 0
                    assert sum(physical_predecessor(colours,power,k).values()) == 0
                targets[k] = terminal_singlet(power,k,colours//2)
            record['full_terminal_singlets'] = targets
        records[f'O{colours}_S{power}'] = record
    return records


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    if not __debug__:
        parser.error('Run with assertions enabled')
    records = run()
    args.out.write_text(json.dumps(records, indent=2)+'\n')
    for key, row in records.items():
        print(key, row['physical_source_relations'], row['physical_terminal_relations'],
              row['relation_tree_rank'], row.get('full_terminal_singlets', {}))
