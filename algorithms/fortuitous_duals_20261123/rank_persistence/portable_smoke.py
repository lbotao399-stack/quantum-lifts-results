#!/usr/bin/env python3
"""Check relocated imports and replay the exact rational chosen-lift control.

Only a temporary child directory is written. No native matrices, large
certificates, or companion files are regenerated by this test.
"""
from pathlib import Path
import argparse
import gzip
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time

HERE = Path(__file__).resolve().parent
SCRIPTS = ['rank_runtime.py', 'dimensions.py', 'lower_rank_scan.py',
           'sp4_outgoing_rank.py', 'exact_rank_control.py']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--positive', type=Path,
                        default=Path(os.environ.get('FORTUITY_POSITIVE_SECTOR',
                                                    str(HERE.parent / 'positive_sector'))))
    parser.add_argument('--output', type=Path, default=HERE / 'portable_smoke.json')
    args = parser.parse_args()
    start = time.monotonic()
    expected = json.loads((HERE / 'exact_rank_control.json').read_text())
    environment = dict(os.environ)
    environment['FORTUITY_POSITIVE_SECTOR'] = str(args.positive.resolve())
    environment['PYTHONDONTWRITEBYTECODE'] = '1'
    environment['OPENBLAS_NUM_THREADS'] = '1'
    with tempfile.TemporaryDirectory(prefix='_portable_smoke_', dir=HERE) as directory:
        relocated = Path(directory)
        for name in SCRIPTS:
            shutil.copy2(HERE / name, relocated / name)
        imports = subprocess.run(
            [sys.executable, '-c',
             'from pathlib import Path; '
             'import dimensions, lower_rank_scan, sp4_outgoing_rank, exact_rank_control; '
             'assert not list(Path.cwd().glob("*.json"))'],
            cwd=relocated, env=environment, capture_output=True, text=True, check=True)
        assert not imports.stdout, imports.stdout
        control = subprocess.run([sys.executable, 'exact_rank_control.py'],
                                 cwd=relocated, env=environment,
                                 capture_output=True, text=True, check=True)
        actual = json.loads((relocated / 'exact_rank_control.json').read_text())
        assert actual['passed'] and expected['passed']
        for key in ['weight', 'cycle_trace_terms', 'stable_derivative_terms', 'alphabet', 'records']:
            assert actual[key] == expected[key], key
        omega_gzip = (args.positive / 'omega_rational.json.gz').read_bytes()
        omega_hash = hashlib.sha256(gzip.decompress(omega_gzip)).hexdigest()
        gzip_hash = hashlib.sha256(omega_gzip).hexdigest()
        assert actual['omega_json_sha256'] == omega_hash
        assert actual['omega_gzip_sha256'] == gzip_hash
        result = {
            'passed': True,
            'relocated_script_count': len(SCRIPTS),
            'imports_stdout_empty': True,
            'imports_created_no_json': True,
            'native_generation_repeated': False,
            'omega_pickle_required': False,
            'original_cycle_terms': actual['cycle_trace_terms'],
            'stable_derivative_terms': actual['stable_derivative_terms'],
            'exact_control_records_reproduced': len(actual['records']),
            'omega_json_sha256': omega_hash,
            'omega_gzip_sha256': gzip_hash,
            'script_sha256': {name: hashlib.sha256((HERE / name).read_bytes()).hexdigest()
                              for name in SCRIPTS},
            'exact_control_seconds': actual['seconds'],
            'seconds': time.monotonic() - start,
            'scope': 'Relocated imports and exact integer/Fraction evaluation only; '
                     'uses the companion pinned input pipeline without editing it.'}
        args.output.write_text(json.dumps(result, indent=2) + '\n')
        print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
