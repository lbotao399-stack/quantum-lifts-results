#!/usr/bin/env python3
"""Full finite-field dual factorization on the genuine Sp(3) omega sector.

The stable formal source, finite trace evaluation, and two adjacent finite
maps are regenerated by the companion positive_sector scripts. This program
performs separate coordinate arithmetic: a dual ell Q_st = b pi on every
formal source, complete boundary annihilation, and a nonzero cycle pairing.
No physical inner product or new normalization is introduced.
"""
from pathlib import Path
import argparse
import hashlib
import json
import sys
import time

import numpy as np
from scipy.sparse import load_npz
from flint import nmod_mat

HERE = Path(__file__).resolve().parent


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--input', type=Path, default=HERE.parent / 'positive_sector')
    ap.add_argument('--output', type=Path, default=HERE / 'sp3_dual_factorization.json')
    args = ap.parse_args()
    start = time.monotonic()
    root = args.input
    ranks = json.loads((root / 'stable_rank_result.json').read_text())
    native = json.loads((root / 'native_frames_result.json').read_text())
    prime = ranks['prime']
    differential = load_npz(root / 'stable_q_columns.npz').tocsr()
    finite = np.load(root / 'finite_evaluation.npz')
    adjacent = np.load(root / 'finite_outgoing.npz')
    evaluation = finite['evaluation'].astype(np.int64)
    boundaries = finite['incoming'].astype(np.int64)
    source_basis = finite['basis_rows']
    finite_outgoing = adjacent['outgoing'].astype(np.int64)
    cycle = adjacent['cycle'].astype(np.int64)
    b = adjacent['functional'].astype(np.int64)
    assert differential.shape == (6020, 2870)
    assert evaluation.shape == (2870, 2689)
    assert boundaries.shape == (2624, 2689)
    assert finite_outgoing.shape == (2689, 1281)

    # b is the unchanged archived finite-evaluation functional. In common
    # formal-source columns its pullback is evaluation @ b.
    pulled_back = evaluation @ b % prime
    minor_sources = ranks['outgoing']['basis_rows']
    minor_targets = ranks['outgoing']['columns']
    assert len(minor_sources) == len(minor_targets) == 1198
    minor = differential[minor_targets][:, minor_sources].T.toarray()
    a = nmod_mat(minor.tolist(), prime)
    determinant = int(a.det())
    assert determinant == ranks['outgoing']['determinant']
    rhs = nmod_mat([[int(pulled_back[j])] for j in minor_sources], prime)
    solution = a.solve(rhs)
    ell = np.zeros(differential.shape[0], dtype=np.int64)
    for j, target in enumerate(minor_targets):
        ell[target] = int(solution[j, 0])
    left = np.asarray(differential.T @ ell).reshape(-1) % prime
    assert np.array_equal(left, pulled_back)

    # These are all formal parents, not just a pivot slice.
    boundary_pairings = boundaries @ b % prime
    assert not np.any(boundary_pairings)
    cycle_values = cycle @ evaluation[source_basis] % prime
    cycle_pairing = int(cycle_values @ b % prime)
    assert cycle_pairing == 1
    assert not np.any(cycle @ finite_outgoing % prime)

    # Stable incoming/outgoing rank saturation, already regenerated in the
    # companion calculation, identifies all universal closed vectors with
    # stable boundaries. Their finite image is the complete finite boundary
    # image. This gives the full dual intersection dimension, not a sampled
    # or known-product lower bound.
    stable_incoming = ranks['incoming']['rank']
    stable_outgoing = ranks['outgoing']['rank']
    assert stable_incoming + stable_outgoing == 2870
    finite_incoming = native['incoming_minor_rank']
    finite_outgoing_rank = native['outgoing_minor_rank']
    intersection_dimension = 2689 - finite_incoming
    stacked_rank_from_complete_complex = stable_outgoing + 2689 - intersection_dimension
    fortuitous_dimension = intersection_dimension - finite_outgoing_rank
    assert (stable_incoming, stable_outgoing) == (1672, 1198)
    assert (finite_incoming, finite_outgoing_rank) == (1607, 1081)
    assert (intersection_dimension, stacked_rank_from_complete_complex, fortuitous_dimension) == (1082, 2805, 1)
    result = {
        'passed': True,
        'group': 'Sp(3)=USp(6)',
        'weight': [3, 3, 5, 0, 0],
        'length': 9,
        'level': 28,
        'prime': prime,
        'equation': 'ell Q_st = b pi',
        'convention': 'b is the original archived target_functional, unchanged; its pairing with the archived cycle is 1',
        'formal_source_equations_checked': 2870,
        'formal_target_coordinate_count': 6020,
        'finite_evaluation_coordinate_count': 2689,
        'finite_boundary_rows_checked': 2624,
        'boundary_pairings_nonzero': int(np.count_nonzero(boundary_pairings)),
        'cycle_outgoing_coordinates_checked': 1281,
        'cycle_pairing': cycle_pairing,
        'stable_incoming_rank': stable_incoming,
        'stable_outgoing_rank': stable_outgoing,
        'stable_cohomology_dimension': 0,
        'finite_incoming_rank': finite_incoming,
        'finite_outgoing_rank': finite_outgoing_rank,
        'finite_cohomology_dimension': 1,
        'dual_intersection_dimension': intersection_dimension,
        'outgoing_coboundary_dual_dimension': finite_outgoing_rank,
        'fortuitous_dual_quotient_dimension': fortuitous_dimension,
        'stacked_rank_derived_from_complete_complex': stacked_rank_from_complete_complex,
        'factorization_minor_determinant': determinant,
        'ell_support': int(np.count_nonzero(ell)),
        'b_support': int(np.count_nonzero(b)),
        'ell': [[int(i), int(ell[i])] for i in np.flatnonzero(ell)],
        'b': [[int(i), int(b[i])] for i in np.flatnonzero(b)],
        'b_pi': pulled_back.tolist(),
        'input_sha256': {name: sha(root / name) for name in [
            'stable_rank_result.json', 'native_frames_result.json',
            'stable_q_columns.npz', 'finite_evaluation.npz', 'finite_outgoing.npz']},
        'seconds': time.monotonic() - start,
        'scope': 'All displayed coefficients and the explicit dual factorization are over the stated finite field. Stable and finite rational dimension conclusions use the companion exact character dimensions, nilpotence, rational cycle and nonzero-minor bridge. The stacked rank here is derived from that complete complex, not a separate dense stacked-matrix elimination. No physical Wick or harmonic projector, new generator or new quantum lift is claimed.'
    }
    args.output.write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps({k: v for k, v in result.items() if k not in ('ell', 'b', 'b_pi', 'input_sha256')}, indent=2))


if __name__ == '__main__':
    main()
